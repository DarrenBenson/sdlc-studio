"""`docs/known-issues.md` is derived from the bug corpus, and this is what makes that true.

The page says a release discloses every open Medium and Low finding by id. A disclosure
maintained by hand decays in the direction that flatters: a bug filed after the page was
written is simply absent, and nothing notices. So the page is generated by
`tools/known_issues.py` at the release cut, and its rules are pinned here on fixtures.

The shipped page is NOT compared with the live corpus here (US0898). That comparison turned
the suite red every time a finding was filed or closed, until somebody hand-edited a record
of a release already shipped; it runs once, at the tag, in `.githooks/pre-push`.
"""

