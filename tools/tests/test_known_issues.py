"""`docs/known-issues.md` is derived from the bug corpus, and this is what makes that true.

The page says a release discloses every open Medium and Low finding by id. A disclosure
maintained by hand decays in the direction that flatters: a bug filed after the page was
written is simply absent, and nothing notices. So the page is generated by
`tools/known_issues.py`, and here the shipped page is compared against what the corpus
implies - in both directions, so a missing row and a stale row each fail.

The page is compared through the GENERATOR rather than by re-deriving the corpus a second
time here. A test that reimplements its subject agrees with itself: both copies would have
to be wrong in the same way to disagree, which is the failure mode a second implementation
is supposed to catch and cannot.

Mutants this must fail on: delete a row from the table; add a row for a bug that is not
open; change the `38 findings: 37 Medium, 1 Low` line without changing the table; change a
row's severity cell; make the generator drop the Low severity from its disclosed set.
"""

